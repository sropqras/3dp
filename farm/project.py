"""Visual-gate artefact: a PrusaSlicer project (.3mf) of exactly what was sliced, for a human to inspect.

The CLI's --export-3mf writes geometry only, so the settings are taken from the config block PrusaSlicer
appends to the G-code it just produced (identical to what sliced it), and the colour changes are added as
PrusaSlicer's own per-print_z custom G-code, so Preview shows the colours on the layer slider.
"""
import re
import subprocess
import time
import zipfile
from pathlib import Path

from . import config

CONFIG_BLOCK = re.compile(r"^; prusaslicer_config = begin\n(.*?)^; prusaslicer_config = end", re.S | re.M)


def export_project(run, slice_cmd: list, gcode: Path, colour_layers: list[float], colours: list[str]) -> Path:
    geometry = run.path(gcode.with_suffix(".geometry.3mf").name)
    out = gcode.with_suffix(".3mf")
    cmd = [c for c in slice_cmd if c not in ("--export-gcode",)]
    cmd[cmd.index("--output") + 1] = str(geometry)
    cmd.insert(len(config.slicer_cmd()), "--export-3mf")
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.returncode != 0 or not geometry.is_file():
        run.fail(f"3MF export failed ({proc.returncode}): {proc.stderr[-300:]}")

    block = CONFIG_BLOCK.search(gcode.read_text(encoding="utf-8"))
    if not block:
        run.fail("no prusaslicer_config block in the G-code to embed in the 3MF")
    settings = block.group(1)
    if colours:
        settings = re.sub(r"^; (extruder_colour|filament_colour) = .*$", rf"; \1 = {colours[0]}", settings, flags=re.M)
    header = f"; generated by PrusaSlicer 2.9.6 on {time.strftime('%Y-%m-%d at %H:%M:%S')} UTC (farm pipeline)\n\n"

    codes = "".join(
        f'<code print_z="{z}" type="0" extruder="1" color="{colours[i + 1] if i + 1 < len(colours) else "#FFFFFF"}" '
        f'extra="" gcode="M600"/>\n' for i, z in enumerate(colour_layers))
    custom = ('<?xml version="1.0" encoding="utf-8"?>\n<custom_gcodes_per_print_z bed_idx="0">\n'
              f'{codes}<mode value="SingleExtruder"/>\n</custom_gcodes_per_print_z>\n')

    with zipfile.ZipFile(geometry) as src, zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as dst:
        for item in src.infolist():
            dst.writestr(item, src.read(item.filename))
        dst.writestr("Metadata/Slic3r_PE.config", header + settings)
        dst.writestr("Metadata/Prusa_Slicer_custom_gcode_per_print_z.xml", custom)
    geometry.unlink()

    run.log(f"project: {out.name} (colour changes at print_z {colour_layers}, colours {colours})")
    run.step("project", file=str(out), colour_layers=colour_layers, colours=colours)
    return out
