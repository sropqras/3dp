"""Stand-in for the PrusaSlicer CLI in offline tests: writes plausible G-code or a geometry 3MF.

Reads the loaded filament ini for the temperatures and volumetric cap, so profile plumbing is exercised.
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from farm import slicer  # noqa: E402

args = sys.argv[1:]
out = Path(args[args.index("--output") + 1])
loads = [Path(args[i + 1]) for i, a in enumerate(args) if a == "--load"]
ini = {}
for f in loads:
    ini.update(dict(re.findall(r"^(\w+) = (.*)$", f.read_text(), re.M)))
if "--export-3mf" in args:
    tri = (0, 0, 1, 100, 100, 0, 150, 100, 0, 100, 150, 4)
    slicer._write_3mf(out, [("piece", [tri])])
    sys.exit(0)
first = float(args[args.index("--first-layer-height") + 1])
layer = float(args[args.index("--layer-height") + 1])
lines = ["; generated by FakeSlicer", "G90", "M83",
         f"START_PRINT EXTRUDER_TEMP={ini.get('first_layer_temperature', '200')} "
         f"BED_TEMP={ini.get('first_layer_bed_temperature', '60')}"]
z = first
while z <= 10 + 1e-9:
    lines += [";LAYER_CHANGE", f";Z:{round(z, 4)}", "G1 X100 Y100 E0.5", "G1 X150 Y150 E0.5"]
    z += layer
lines += ["PRINT_END", "; filament used [g] = 21.5", "; estimated printing time (normal mode) = 1h 2m 3s",
          "; prusaslicer_config = begin",
          f"; filament_max_volumetric_speed = {ini.get('filament_max_volumetric_speed', '0')}",
          "; extruder_colour = \"\"", "; prusaslicer_config = end"]
out.write_text("\n".join(lines) + "\n")
