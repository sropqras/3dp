"""Golden G-code check: the refactors must not change what reaches a printer.

    python3 tests/golden.py record   # after an INTENDED change (new slicer, new preset): rewrite the hashes
    python3 tests/golden.py check    # every phase: same job -> same normalised G-code

Needs likhan-maker (FARM_LIKHAN_URL) and the slicer (FARM_PRUSASLICER); never contacts a printer (no --upload).
The default font is used, so the licensed font is never needed here. Hashes are per slicer version: a check
against another version says so instead of failing on a meaningless diff.
"""
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
JOBS = sorted((REPO / "tests" / "fixtures").glob("golden_*.json"))
STORE = REPO / "tests" / "golden"
# header lines that carry the time of slicing
VOLATILE = re.compile(r"^; generated by |^; prusaslicer_config = |^;\s*(date|time)\b", re.I)


def slicer_version() -> str:
    from farm import config
    out = subprocess.run(config.slicer_cmd() + ["--help"], capture_output=True, text=True).stdout
    m = re.search(r"PrusaSlicer-(\S+)", out)
    return m.group(1) if m else "unknown"


def normalised_hash(gcode: Path) -> str:
    h = hashlib.sha256()
    for line in gcode.read_text(encoding="utf-8").splitlines():
        if not VOLATILE.match(line):
            h.update(line.encode() + b"\n")
    return h.hexdigest()


def run_job(job: Path) -> dict:
    with tempfile.TemporaryDirectory() as tmp:
        env = dict(os.environ, FARM_RUNS_DIR=tmp)
        proc = subprocess.run([sys.executable, "-m", "farm", "run", str(job)], cwd=REPO, env=env,
                              capture_output=True, text=True)
        if proc.returncode != 0:
            raise SystemExit(f"{job.name}: farm run failed\n{proc.stdout[-1500:]}{proc.stderr[-1500:]}")
        gcodes = sorted(Path(tmp).glob("*/*.gcode"))
        return {g.name: normalised_hash(g) for g in gcodes}


def main(mode: str) -> int:
    sys.path.insert(0, str(REPO))
    version = slicer_version()
    STORE.mkdir(exist_ok=True)
    bad = 0
    for job in JOBS:
        got = run_job(job)
        ref = STORE / f"{job.stem}.json"
        if mode == "record":
            ref.write_text(json.dumps({"slicer": version, "gcode": got}, indent=2) + "\n")
            print(f"recorded {job.name}: {got}")
            continue
        want = json.loads(ref.read_text())
        if want["slicer"] != version:
            print(f"SKIP {job.name}: golden recorded with PrusaSlicer {want['slicer']}, this is {version} (re-record)")
            continue
        ok = got == want["gcode"]
        bad += not ok
        print(f"{'OK  ' if ok else 'DIFF'} {job.name}" + ("" if ok else f"\n  want {want['gcode']}\n  got  {got}"))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else "check"))
